import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildAllApks } from '../apk-builder';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');

console.log('=== Building Signed Android APK Files (AXML + DEX + ARSC + v1/v2 Signatures) ===');
const result = buildAllApks(rootDir, true);

const mdPath = path.resolve(rootDir, 'BrokerBridgeSync/BROKER_BRIDGE_SYNC_FULL_APK.md');
const mdContent = fs.existsSync(mdPath) ? fs.readFileSync(mdPath, 'utf-8') : '';
try {
  fs.writeFileSync(path.resolve(rootDir, 'public/BROKER_BRIDGE_SYNC_FULL_APK.md'), mdContent, 'utf-8');
} catch {}

const prebuiltTsPath = path.resolve(rootDir, 'src/services/prebuiltApks.ts');
const prebuiltTsContent = `// Auto-generated by scripts/build-apk.ts — DO NOT EDIT MANUALLY
export const FULL_APK_MARKDOWN = ${JSON.stringify(mdContent)};

export const PREBUILT_APKS = {
  brokerBridge: {
    metadata: ${JSON.stringify(result.brokerBridge.metadata, null, 2)},
    base64: ${JSON.stringify(result.brokerBridge.apkBuffer.toString('base64'))},
  },
  goldTerminal: {
    metadata: ${JSON.stringify(result.goldTerminal.metadata, null, 2)},
    base64: ${JSON.stringify(result.goldTerminal.apkBuffer.toString('base64'))},
  },
} as const;

export function triggerEmbeddedApkDownload(which: 'brokerBridge' | 'goldTerminal'): {
  fileName: string;
  sizeBytes: number;
} {
  const item = PREBUILT_APKS[which];
  const binaryStr = window.atob(item.base64);
  const len = binaryStr.length;
  const bytes = new Uint8Array(len);
  for (let i = 0; i < len; i++) {
    bytes[i] = binaryStr.charCodeAt(i);
  }
  const blob = new Blob([bytes], { type: 'application/vnd.android.package-archive' });
  const blobUrl = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = blobUrl;
  a.download = item.metadata.fileName;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(blobUrl), 10000);
  return { fileName: item.metadata.fileName, sizeBytes: len };
}

export function triggerMarkdownDownload(): { fileName: string; sizeBytes: number } {
  const fileName = 'BROKER_BRIDGE_SYNC_FULL_APK.md';
  const blob = new Blob([FULL_APK_MARKDOWN], { type: 'text/markdown;charset=utf-8' });
  const blobUrl = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = blobUrl;
  a.download = fileName;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(blobUrl), 10000);
  return { fileName, sizeBytes: blob.size };
}
`;

fs.writeFileSync(prebuiltTsPath, prebuiltTsContent, 'utf-8');
console.log('Generated src/services/prebuiltApks.ts successfully.');

console.log('\n[1] BrokerBridgeSync APK:');
console.log(JSON.stringify(result.brokerBridge.metadata, null, 2));

console.log('\n[2] SCHEVANKA Gold Terminal APK:');
console.log(JSON.stringify(result.goldTerminal.metadata, null, 2));

